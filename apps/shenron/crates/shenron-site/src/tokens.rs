// Design tokens: the single source of truth for the generated stylesheet.
//
// This file is `include!`d by `build.rs` (which renders `style/main.css`) and
// compiled as a normal module of the crate, so it must stay dependency-free.
// Palette: HCT-derived Shenron brand (orange ki, Kame blue, parchment paper).

/// A named color exposed as `--color-<name>`.
pub struct ColorToken {
    pub name: &'static str,
    pub value: &'static str,
}

/// Light scheme.
pub const COLORS_LIGHT: &[ColorToken] = &[
    ColorToken { name: "primary", value: "#e8641b" },
    ColorToken { name: "on-primary", value: "#fff8f2" },
    ColorToken { name: "secondary", value: "#1f5fa8" },
    ColorToken { name: "on-secondary", value: "#f1f6fd" },
    ColorToken { name: "surface", value: "#faf5ec" },
    ColorToken { name: "surface-alt", value: "#f1e9d9" },
    ColorToken { name: "on-surface", value: "#1f1a14" },
    ColorToken { name: "on-surface-muted", value: "#5e554a" },
    ColorToken { name: "outline", value: "#c9bfae" },
    ColorToken { name: "reader-bg", value: "#0d0c0b" },
];

/// Dark scheme (applied under `prefers-color-scheme: dark`).
pub const COLORS_DARK: &[ColorToken] = &[
    ColorToken { name: "primary", value: "#ff9a4d" },
    ColorToken { name: "on-primary", value: "#2a1304" },
    ColorToken { name: "secondary", value: "#7fb2ff" },
    ColorToken { name: "on-secondary", value: "#06203f" },
    ColorToken { name: "surface", value: "#141210" },
    ColorToken { name: "surface-alt", value: "#1e1a16" },
    ColorToken { name: "on-surface", value: "#f3ece0" },
    ColorToken { name: "on-surface-muted", value: "#b5aa99" },
    ColorToken { name: "outline", value: "#4a4036" },
    ColorToken { name: "reader-bg", value: "#000000" },
];

/// Spacing scale in rem, exposed as `--space-0` .. `--space-N`.
pub const SPACE_SCALE_REM: &[f32] = &[0.0, 0.25, 0.5, 0.75, 1.0, 1.5, 2.0, 3.0, 4.0, 6.0];

/// Radii in rem, exposed as `--radius-<name>`.
pub const RADII: &[(&str, f32)] = &[("sm", 0.25), ("md", 0.5), ("lg", 1.0), ("full", 999.0)];

/// Typography (no generic default fonts: the brand stack is declared here and
/// the actual face is shipped by the design system, system-ui is the fallback).
pub const FONT_BODY: &str = "\"Shenron Sans\", \"Noto Sans JP\", system-ui, sans-serif";
pub const FONT_DISPLAY: &str = "\"Shenron Display\", \"Noto Sans JP\", system-ui, sans-serif";
pub const MEASURE_CH: u16 = 72;
pub const CONTENT_MAX_WIDTH_REM: f32 = 72.0;

fn push_vars(out: &mut String, colors: &[ColorToken]) {
    for c in colors {
        out.push_str(&format!("  --color-{}: {};\n", c.name, c.value));
    }
}

/// Renders the whole stylesheet from the tokens above.
pub fn render_css() -> String {
    let mut css = String::with_capacity(4096);
    css.push_str("/* GENERATED by build.rs from src/tokens.rs. Do not edit. */\n");
    css.push_str(":root {\n");
    css.push_str("  color-scheme: light dark;\n");
    push_vars(&mut css, COLORS_LIGHT);
    for (i, rem) in SPACE_SCALE_REM.iter().enumerate() {
        css.push_str(&format!("  --space-{i}: {rem}rem;\n"));
    }
    for (name, rem) in RADII {
        css.push_str(&format!("  --radius-{name}: {rem}rem;\n"));
    }
    css.push_str(&format!("  --font-body: {FONT_BODY};\n"));
    css.push_str(&format!("  --font-display: {FONT_DISPLAY};\n"));
    css.push_str(&format!("  --measure: {MEASURE_CH}ch;\n"));
    css.push_str(&format!("  --content-max: {CONTENT_MAX_WIDTH_REM}rem;\n"));
    css.push_str("}\n");
    css.push_str("@media (prefers-color-scheme: dark) {\n  :root {\n");
    push_vars(&mut css, COLORS_DARK);
    css.push_str("  }\n}\n");

    // Structural rules, all expressed through the variables above.
    css.push_str(concat!(
        "*, *::before, *::after { box-sizing: border-box; }\n",
        "html { font-family: var(--font-body); background: var(--color-surface); color: var(--color-on-surface); }\n",
        "body { margin: 0; min-height: 100dvh; display: grid; grid-template-rows: auto 1fr auto; }\n",
        "a { color: var(--color-secondary); text-decoration-thickness: from-font; }\n",
        "h1, h2, h3 { font-family: var(--font-display); line-height: 1.1; margin: 0 0 var(--space-4); }\n",
        ".site-header, .site-footer { padding: var(--space-4) var(--space-5); background: var(--color-surface-alt); border-block: 1px solid var(--color-outline); }\n",
        ".site-header nav { display: flex; gap: var(--space-4); flex-wrap: wrap; align-items: center; }\n",
        ".site-header .brand { font-family: var(--font-display); color: var(--color-primary); font-weight: 700; }\n",
        ".lang-switch { margin-inline-start: auto; display: flex; gap: var(--space-2); }\n",
        ".lang-switch a[aria-current='true'] { color: var(--color-primary); font-weight: 700; }\n",
        "main { width: min(100% - 2 * var(--space-5), var(--content-max)); margin-inline: auto; padding-block: var(--space-6); }\n",
        "main p { max-width: var(--measure); }\n",
        ".card-grid { display: grid; gap: var(--space-4); grid-template-columns: repeat(auto-fill, minmax(14rem, 1fr)); padding: 0; list-style: none; }\n",
        ".card { padding: var(--space-4); border: 1px solid var(--color-outline); border-radius: var(--radius-md); background: var(--color-surface-alt); }\n",
        ".reader { display: grid; gap: var(--space-3); }\n",
        ".reader canvas { width: 100%; aspect-ratio: 2 / 3; background: var(--color-reader-bg); border-radius: var(--radius-sm); display: block; }\n",
        ".reader-nav { display: flex; justify-content: space-between; gap: var(--space-3); }\n",
        ".muted { color: var(--color-on-surface-muted); }\n",
    ));
    css
}
